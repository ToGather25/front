/* 데모용: 언제 실행해도 "이번 달 전후"에 행사가 보이도록 오늘 기준으로 날짜를 생성한다.
   실 API 전환 시(VITE_USE_DUMMY=false) 이 파일은 통째로 우회되므로 영향 없음. */
const pad = (n) => String(n).padStart(2, "0");
const iso = (dt) => `${dt.getFullYear()}-${pad(dt.getMonth() + 1)}-${pad(dt.getDate())}`;

const NOW = new Date();
const TODAY = iso(NOW);
const MONTH_START = new Date(NOW.getFullYear(), NOW.getMonth(), 1);
const DAYS_IN_CURRENT_MONTH = new Date(
  MONTH_START.getFullYear(),
  MONTH_START.getMonth() + 1,
  0,
).getDate();
const TODAY_DAY = NOW.getDate();

/** 이번 달 1일 기준 monthOffset개월 뒤의 day일 */
const d = (monthOffset, day) =>
  iso(new Date(MONTH_START.getFullYear(), MONTH_START.getMonth() + monthOffset, day));

/** "YYYY-MM-DD"에서 days만큼 이동 */
const shift = (dateStr, days) => {
  const [y, m, dd] = dateStr.split("-").map(Number);
  return iso(new Date(y, m - 1, dd + days));
};

const clampDay = (day) => Math.min(Math.max(day, 1), DAYS_IN_CURRENT_MONTH);
/** 이번 달 내에서 오늘보다 offset일 이전 */
const pastDay = (offset) => clampDay(TODAY_DAY - offset);
/** 이번 달 내에서 오늘보다 offset일 이후 */
const futureDay = (offset) => clampDay(TODAY_DAY + offset);

